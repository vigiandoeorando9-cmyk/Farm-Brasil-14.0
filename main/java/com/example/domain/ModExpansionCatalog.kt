private fun h2p(
    id: String,
    name: String,
    category: String,
    version: String,
    sizeMb: Double,
    author: String,
    desc: String,
    installed: Boolean = false,
    deps: List<String>? = null,
    android: Boolean = true,
    windows: Boolean = true,
    lifecycle: ModValidationStatus? = null,
    minVer: String = "3.0",
) = HubPackEntity(
    packId = id,
    name = name,
    category = category,
    version = version,
    sizeMb = sizeMb,
    author = author,
    description = desc,
    minGameVersion = minVer,
    installed = installed,
    localPath = if (installed) "builtin://hub/$id.json" else null,
    installedAtEpochMs = if (installed) 1732000000000L else 0L,
    dependencies = deps,
    androidCompatible = android,
    windowsCompatible = windows,
    lifecycleState = lifecycle,
)

