private fun modVeh(
    id: String,
    brand: String,
    model: String,
    category: VehicleCategory,
    era: String,
    year: Int,
    hp: Double,
    maxKmh: Double,
    weightKg: Double,
    priceBrl: Double,
    bodyStyle: VehicleBodyStyle,
    wheelLayout: WheelLayout,
    primaryRgb: RgbTriple,
    accentRgb: RgbTriple,
    dims: DimTriple,
    hitches: List<HitchType>,
    tankL: Double,
    sound: String,
    subType: String,
    desc: String,
    packId: String,
): VehicleDef = VehicleDef(
    id = id,
    brand = brand,
    model = model,
    category = category,
    era = era,
    modelYear = year,
    horsepower = hp,
    maxTorqueNm = hp * 4.1,
    maxSpeedKmh = maxKmh,
    fuelCapacityL = (hp * 1.45).coerceAtLeast(110.0),
    weightKg = weightKg,
    priceBrl = priceBrl,
    supportedHitches = hitches,
    primaryColorRgb = primaryRgb,
    accentColorRgb = accentRgb,
    bodyStyle = bodyStyle,
    wheelLayout = wheelLayout,
    hasCab = bodyStyle != VehicleBodyStyle.CLASSIC_2WD && bodyStyle != VehicleBodyStyle.COMPACT_OPEN,
    dimensionsM = dims,
    turnRateDegPerSec = if (bodyStyle == VehicleBodyStyle.TRUCK) 42.0 else 50.0,
    soundProfile = sound,
    hasGrainTank = tankL > 0.0 && category == VehicleCategory.COLHEITADEIRA,
    tankCapacityL = tankL,
    gpsReady = year >= 2012,
    description = desc,
    requiredModPackId = packId,
    subTypeLabel = subType,
)

